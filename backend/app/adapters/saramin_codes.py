"""현행 행정 시도 코드 17개를 사람인 1차 근무지 코드(loc_mcd)로 변환한다.

출처: https://oapi.saramin.co.kr/guide/code-table2 (1차 근무지/지역 코드).
강원·전북은 현행 행정 코드 51·52만 받는다. 사람인 112000의 표기는 '전남광주'다.
"""

_REGION_CODES: dict[str, str] = {
    "11": "101000",  # 서울
    "26": "106000",  # 부산
    "27": "104000",  # 대구
    "28": "108000",  # 인천
    "29": "103000",  # 광주
    "30": "105000",  # 대전
    "31": "107000",  # 울산
    "36": "118000",  # 세종
    "41": "102000",  # 경기
    "43": "114000",  # 충북
    "44": "115000",  # 충남
    "46": "112000",  # 전남
    "47": "111000",  # 경북
    "48": "110000",  # 경남
    "50": "116000",  # 제주
    "51": "109000",  # 강원
    "52": "113000",  # 전북
}


def to_loc_mcd(region: str) -> str:
    """지원하지 않는 행정 코드는 검색 범위를 넓히지 않고 거부한다."""
    try:
        return _REGION_CODES[region]
    except KeyError:
        raise ValueError(f"Unsupported administrative region code: {region}") from None
